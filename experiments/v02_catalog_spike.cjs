/**
 * v0.2C PRIVATE catalog-identity spike (not product).
 *
 * Remints all DBPF instance IDs so the package can coexist with the donor,
 * rewrites STBL name/description, patches OBJD string keys + price, renames COBJ.
 *
 * Open-source only: @s4tk/models + @s4tk/hashing (MIT).
 * Does NOT vendor Sims 4 Studio code.
 * Does NOT modify MLOD geometry bytes beyond embedded TGI instance remaps.
 * Does NOT modify DST pixel payloads.
 *
 * Usage:
 *   node experiments/v02_catalog_spike.cjs \
 *     --package output/v02_texture_spike.package \
 *     --donor "C:/Users/Cliente-TechNew/Desktop/TheSims4Tool/Vaso.package" \
 *     --name "CCStudio Test Mug" \
 *     --description "Generated by CC Studio" \
 *     --price 10 \
 *     --output output/v02_catalog_spike.package
 */

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { Package, StringTableResource, RawResource } = require("@s4tk/models");
const { fnv32 } = require("@s4tk/hashing");

function arg(name, def = null) {
  const i = process.argv.indexOf(name);
  if (i >= 0 && i + 1 < process.argv.length) return process.argv[i + 1];
  return def;
}

function sha256(buf) {
  return crypto.createHash("sha256").update(buf).digest("hex");
}

function getBuf(value) {
  if (!value) return Buffer.alloc(0);
  if (Buffer.isBuffer(value)) return value;
  if (typeof value.getBuffer === "function") return Buffer.from(value.getBuffer());
  if (value.buffer) return Buffer.from(value.buffer);
  if (value instanceof Uint8Array) return Buffer.from(value);
  return Buffer.from(value);
}

function u64le(n) {
  const b = Buffer.alloc(8);
  b.writeBigUInt64LE(BigInt(n));
  return b;
}

function replaceU64(buf, oldVal, newVal) {
  const oldB = u64le(oldVal);
  const newB = u64le(newVal);
  let count = 0;
  const out = Buffer.from(buf);
  for (let i = 0; i <= out.length - 8; i++) {
    if (out.compare(oldB, 0, 8, i, i + 8) === 0) {
      newB.copy(out, i);
      count++;
      i += 7;
    }
  }
  return { buf: out, count };
}

function randomU56() {
  // 56-bit random (fits STBL base / general instance without locale byte)
  const hi = crypto.randomBytes(3).readUIntBE(0, 3) & 0x00ffffff;
  const lo = crypto.randomBytes(4).readUInt32BE(0);
  return (BigInt(hi) << 32n) | BigInt(lo);
}

function randomU64() {
  const b = crypto.randomBytes(8);
  b[0] &= 0x7f; // keep positive / avoid sign weirdness in some tools
  return b.readBigUInt64BE(0);
}

function peelCobj(buf) {
  const ver = buf.readUInt16LE(0);
  const unk = buf.readUInt32LE(2);
  const nlen = buf.readUInt32LE(6);
  const name = buf.slice(10, 10 + nlen).toString("ascii");
  const tlen = buf.readUInt32LE(10 + nlen);
  const tuning = buf.slice(14 + nlen, 14 + nlen + tlen).toString("ascii");
  const restOff = 14 + nlen + tlen;
  return { ver, unk, name, tuning, restOff, rest: buf.slice(restOff) };
}

function rebuildCobj(peeled, newName) {
  const nameBuf = Buffer.from(newName, "ascii");
  const tuningBuf = Buffer.from(peeled.tuning, "ascii");
  const out = Buffer.alloc(2 + 4 + 4 + nameBuf.length + 4 + tuningBuf.length + peeled.rest.length);
  let pos = 0;
  out.writeUInt16LE(peeled.ver, pos); pos += 2;
  // unk field in donor tracked byte length of following name block region roughly;
  // recompute as nameLen + tuningLen + rest? Observed: equals (name+tuning+some). Keep old delta.
  const unk = 4 + nameBuf.length + 4 + tuningBuf.length + (peeled.unk - (4 + Buffer.byteLength(peeled.name) + 4 + Buffer.byteLength(peeled.tuning)));
  out.writeUInt32LE(unk > 0 ? unk : peeled.unk, pos); pos += 4;
  out.writeUInt32LE(nameBuf.length, pos); pos += 4;
  nameBuf.copy(out, pos); pos += nameBuf.length;
  out.writeUInt32LE(tuningBuf.length, pos); pos += 4;
  tuningBuf.copy(out, pos); pos += tuningBuf.length;
  peeled.rest.copy(out, pos);
  return out;
}

function main() {
  const pkgPath = arg("--package");
  const donorPath = arg("--donor");
  const name = arg("--name", "CCStudio Test Mug");
  const description = arg("--description", "Generated by CC Studio");
  const price = parseFloat(arg("--price", "10"));
  const output = arg("--output", path.resolve(__dirname, "../output/v02_catalog_spike.package"));
  const reportPath = arg("--report", path.resolve(__dirname, "../output/v02_catalog_spike_report.json"));
  const logPath = arg("--log", path.resolve(__dirname, "../output/v02_catalog_spike_run.log"));

  const lines = [];
  const log = (m) => {
    console.log(m);
    lines.push(m);
  };

  if (!pkgPath || !fs.existsSync(pkgPath)) {
    console.error("missing --package");
    process.exit(1);
  }

  const beforeBuf = fs.readFileSync(pkgPath);
  const pkg = Package.from(beforeBuf);
  const donorInstances = new Set();
  if (donorPath && fs.existsSync(donorPath)) {
    const donor = Package.from(fs.readFileSync(donorPath));
    for (const e of donor.entries) donorInstances.add(BigInt(e.key.instance));
  }

  // Snapshot content hashes by type before remint
  const before = { tgis: [], dst: {}, mlod: {}, objd: null, cobj: null, stbl0: null };
  for (const e of pkg.entries) {
    const t = Number(e.key.type);
    const g = Number(e.key.group);
    const i = BigInt(e.key.instance);
    const buf = getBuf(e.value);
    const tgi = `${t.toString(16)}:${g.toString(16)}:${i.toString(16)}`;
    before.tgis.push(tgi);
    if (t === 0x00b2d882) before.dst[tgi] = sha256(buf);
    if (t === 0x01d10f34 && g === 0) before.mlod[tgi] = { sha: sha256(buf), len: buf.length };
    if (t === 0x319e4f1d) before.objd = { tgi, sha: sha256(buf), len: buf.length, i: i.toString(16) };
    if (t === 0xc0db5ae7) {
      const peeled = peelCobj(buf);
      before.cobj = { tgi, sha: sha256(buf), ...peeled, i: i.toString(16) };
    }
    if (t === 0x220557da && Number(i >> 56n) === 0) {
      const stbl = StringTableResource.from(buf);
      before.stbl0 = [...stbl.entries].map((x) => ({ key: (Number(x.key) >>> 0).toString(16), value: x.value }));
    }
  }

  log(`[catalog] input=${pkgPath}`);
  log(`[catalog] entries=${pkg.size}`);
  log(`[catalog] before OBJD=${before.objd && before.objd.tgi}`);
  log(`[catalog] before COBJ name=${before.cobj && before.cobj.name} tuning=${before.cobj && before.cobj.tuning}`);

  // Build instance remap. Preserve STBL locale high byte.
  const oldInstances = [...new Set(pkg.entries.map((e) => BigInt(e.key.instance)))];
  const remap = new Map();
  const used = new Set(donorInstances);
  for (const old of oldInstances) {
    const locale = old >> 56n;
    let neu;
    let guard = 0;
    do {
      if (locale !== 0n) {
        neu = (locale << 56n) | randomU56();
      } else {
        // Prefer full 64-bit for non-localized resources
        neu = randomU64();
        // If this old id looked like STBL base-only (high byte 0), keep high byte 0
        if (old < 1n << 56n) neu = neu & ((1n << 56n) - 1n);
      }
      guard++;
      if (guard > 1000) throw new Error("could not allocate unique instance");
    } while (used.has(neu) || [...remap.values()].includes(neu));
    remap.set(old, neu);
    used.add(neu);
  }

  const nameKey = fnv32(name) >>> 0;
  const descKey = fnv32(description) >>> 0;
  // Avoid accidental collision with existing keys
  const oldNameKey = before.stbl0 && before.stbl0[0] ? parseInt(before.stbl0[0].key, 16) : 0;
  const oldDescKey = before.stbl0 && before.stbl0[1] ? parseInt(before.stbl0[1].key, 16) : 0;

  log(`[catalog] new nameKey=0x${nameKey.toString(16)} descKey=0x${descKey.toString(16)}`);
  log(`[catalog] remapped ${remap.size} instances`);

  const replaceCounts = {};
  const newEntries = [];

  for (const e of pkg.entries) {
    const t = Number(e.key.type);
    const g = Number(e.key.group);
    const oldI = BigInt(e.key.instance);
    const newI = remap.get(oldI);
    let buf = getBuf(e.value);

    // Remap any embedded instance IDs inside payload
    for (const [o, n] of remap.entries()) {
      const r = replaceU64(buf, o, n);
      if (r.count) {
        replaceCounts[`${o.toString(16)}->${n.toString(16)}`] =
          (replaceCounts[`${o.toString(16)}->${n.toString(16)}`] || 0) + r.count;
        buf = r.buf;
      }
    }

    if (t === 0x220557da) {
      const stbl = StringTableResource.from(buf);
      // Replace old keys with new name/desc across all locales
      const nextEntries = [];
      let sawName = false;
      let sawDesc = false;
      for (const ent of stbl.entries) {
        const k = Number(ent.key) >>> 0;
        if (k === oldNameKey) {
          nextEntries.push({ key: nameKey, value: name });
          sawName = true;
        } else if (k === oldDescKey) {
          nextEntries.push({ key: descKey, value: description });
          sawDesc = true;
        } else {
          nextEntries.push({ key: k, value: ent.value });
        }
      }
      if (!sawName) nextEntries.push({ key: nameKey, value: name });
      if (!sawDesc) nextEntries.push({ key: descKey, value: description });
      const next = new StringTableResource(nextEntries);
      buf = getBuf(next);
    }

    if (t === 0x319e4f1d) {
      // Patch string keys at observed offsets 8 / 12 (validated A/B diff)
      if (buf.length >= 16) {
        buf.writeUInt32LE(nameKey, 8);
        buf.writeUInt32LE(descKey, 12);
      }
      // Price: S4S vase (NovoVasoTeste2) stores catalog cost as f32 at offset 90.
      // Force-write requested price there for Build/Buy. Also mirror as u32@16 when
      // that slot looks like a small integer cost/flag field (donor had 1; S4S had 0x514).
      if (buf.length > 94) {
        buf.writeFloatLE(price, 90);
      }
      if (buf.length > 20) {
        const slot16 = buf.readUInt32LE(16);
        if (slot16 <= 100000) buf.writeUInt32LE(price | 0, 16);
      }
      if (buf.length > 139) {
        const curU = buf.readUInt32LE(135);
        if (curU <= 5000) buf.writeUInt32LE(price | 0, 135);
      }
      log(`[catalog] OBJD patched keys + price=${price}`);
    }

    if (t === 0xc0db5ae7) {
      const peeled = peelCobj(buf);
      const stamp = new Date().toISOString().replace(/[-:TZ.]/g, "").slice(0, 17);
      const newInternal = `CCStudio_TestMug_${stamp}_set1`;
      buf = rebuildCobj(peeled, newInternal);
      // Remap again on rebuilt buffer (rest still has TGIs)
      for (const [o, n] of remap.entries()) {
        const r = replaceU64(buf, o, n);
        if (r.count) buf = r.buf;
      }
      log(`[catalog] COBJ internal name -> ${newInternal} (tuning kept: ${peeled.tuning})`);
    }

    newEntries.push({
      key: { type: t, group: g, instance: newI },
      value: RawResource.from(buf),
    });
  }

  // Mutate the loaded package in place (Package has no static create()).
  const entriesSnapshot = [...pkg.entries];
  // Clear by removing from end to start if API supports delete; else rebuild via merge of none + add.
  // MappedModel typically supports clear/add — try constructing empty Package.
  const outPkg = new Package();
  for (const e of newEntries) {
    outPkg.add(e.key, e.value);
  }
  const outBuf = Buffer.from(outPkg.getBuffer());
  void entriesSnapshot;
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, outBuf);
  log(`[catalog] wrote ${output} (${outBuf.length} bytes)`);

  // Re-open validations (loadRaw: avoid S4TK mis-parsing Buy/Build OBJD as OBJDEF)
  const verify = Package.from(fs.readFileSync(output), { loadRaw: true });
  const after = { tgis: [], dst: {}, mlod: {}, objd: null, cobj: null, stbl0: null, sharedWithDonor: [] };
  for (const e of verify.entries) {
    const t = Number(e.key.type);
    const g = Number(e.key.group);
    const i = BigInt(e.key.instance);
    const buf = getBuf(e.value);
    const tgi = `${t.toString(16)}:${g.toString(16)}:${i.toString(16)}`;
    after.tgis.push(tgi);
    if (donorInstances.has(i)) after.sharedWithDonor.push(tgi);
    if (t === 0x00b2d882) after.dst[tgi] = sha256(buf);
    if (t === 0x01d10f34 && g === 0) after.mlod[tgi] = { sha: sha256(buf), len: buf.length };
    if (t === 0x319e4f1d) {
      after.objd = {
        tgi,
        i: i.toString(16),
        sha: sha256(buf),
        nameKey: "0x" + buf.readUInt32LE(8).toString(16),
        descKey: "0x" + buf.readUInt32LE(12).toString(16),
        f32_90: buf.length > 94 ? buf.readFloatLE(90) : null,
        u32_135: buf.length > 139 ? buf.readUInt32LE(135) : null,
      };
    }
    if (t === 0xc0db5ae7) {
      const peeled = peelCobj(buf);
      after.cobj = { tgi, i: i.toString(16), ...peeled };
    }
    if (t === 0x220557da && Number(i >> 56n) === 0) {
      const stbl = StringTableResource.from(buf);
      after.stbl0 = [...stbl.entries].map((x) => ({ key: (Number(x.key) >>> 0).toString(16), value: x.value }));
    }
  }

  // DST content equality: compare hashes ignoring TGI identity — match by size/sha set
  const beforeDstShas = Object.values(before.dst).sort();
  const afterDstShas = Object.values(after.dst).sort();
  const dstContentSame = JSON.stringify(beforeDstShas) === JSON.stringify(afterDstShas);

  const beforeMlodSha = Object.values(before.mlod)[0];
  const afterMlodSha = Object.values(after.mlod)[0];

  const objdChanged = before.objd.i !== after.objd.i;
  const cobjChanged = before.cobj.i !== after.cobj.i;
  const stblHasName = after.stbl0.some((e) => e.value === name);
  const stblHasDesc = after.stbl0.some((e) => e.value === description);
  const noDonorOverlap = after.sharedWithDonor.length === 0;
  const cobjObjdSame = after.objd.i === after.cobj.i;

  const programmaticPass =
    objdChanged &&
    cobjChanged &&
    cobjObjdSame &&
    stblHasName &&
    stblHasDesc &&
    noDonorOverlap &&
    dstContentSame &&
    verify.size === pkg.size;

  const report = {
    status: programmaticPass ? "PASS" : "FAIL",
    note: "Programmatic identity remint. Manual in-game search still required.",
    tuning_inherited: after.cobj.tuning,
    tuning_note:
      after.cobj.tuning === "object_light_table"
        ? "Donor lamp tuning retained — object may still behave as lighting semantically."
        : after.cobj.tuning,
    inputs: { package: pkgPath, donor: donorPath, name, description, price },
    output,
    before: {
      objd: before.objd,
      cobj: { tgi: before.cobj.tgi, name: before.cobj.name, tuning: before.cobj.tuning, i: before.cobj.i },
      stbl0: before.stbl0,
      dst_shas: beforeDstShas,
      mlod0: beforeMlodSha,
    },
    after: {
      objd: after.objd,
      cobj: { tgi: after.cobj.tgi, name: after.cobj.name, tuning: after.cobj.tuning, i: after.cobj.i },
      stbl0: after.stbl0,
      dst_shas: afterDstShas,
      mlod0: afterMlodSha,
      shared_with_donor: after.sharedWithDonor,
    },
    invariants: {
      objd_instance_changed: objdChanged,
      cobj_instance_changed: cobjChanged,
      cobj_objd_instance_equal: cobjObjdSame,
      stbl_has_name: stblHasName,
      stbl_has_description: stblHasDesc,
      no_donor_instance_overlap: noDonorOverlap,
      dst_content_hashes_unchanged: dstContentSame,
      mlod0_hash_changed_expected: beforeMlodSha && afterMlodSha ? beforeMlodSha.sha !== afterMlodSha.sha : null,
      mlod0_hash_change_reason: "Embedded texture/model instance u64s remapped inside MLOD payload",
      entry_count_same: verify.size === pkg.size,
    },
    remap_size: remap.size,
    embedded_u64_replace_ops: Object.keys(replaceCounts).length,
    licenses: {
      "@s4tk/models": "MIT",
      "@s4tk/hashing": "MIT",
    },
  };

  fs.writeFileSync(reportPath, JSON.stringify(report, null, 2));
  fs.writeFileSync(logPath, lines.join("\n") + "\n" + JSON.stringify(report.invariants, null, 2) + "\n");
  log(`[catalog] report=${reportPath}`);
  log(`[catalog] RESULT ${report.status}`);
  process.exit(programmaticPass ? 0 : 1);
}

main();
