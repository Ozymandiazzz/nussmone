"""
v0.2C catalog-identity spike wrapper.

Delegates to experiments/v02_catalog_spike.cjs (@s4tk/models + @s4tk/hashing, MIT).
Does not modify ccstudio.py or mesh/texture pipeline logic.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JS = Path(__file__).resolve().parent / "v02_catalog_spike.cjs"


def main() -> int:
    p = argparse.ArgumentParser(prog="v02_catalog_spike")
    p.add_argument("--package", required=True, help="validated mesh+diffuse package")
    p.add_argument("--donor", required=True, help="original donor/template package")
    p.add_argument("--name", default="CCStudio Test Mug")
    p.add_argument("--description", default="Generated by CC Studio")
    p.add_argument("--price", type=float, default=10.0)
    p.add_argument("--output", default=str(ROOT / "output" / "v02_catalog_spike.package"))
    p.add_argument("--report", default=str(ROOT / "output" / "v02_catalog_spike_report.json"))
    p.add_argument("--log", default=str(ROOT / "output" / "v02_catalog_spike_run.log"))
    args = p.parse_args()

    cmd = [
        "node",
        str(JS),
        "--package",
        args.package,
        "--donor",
        args.donor,
        "--name",
        args.name,
        "--description",
        args.description,
        "--price",
        str(args.price),
        "--output",
        args.output,
        "--report",
        args.report,
        "--log",
        args.log,
    ]
    print(" ".join(cmd), flush=True)
    return subprocess.call(cmd)


if __name__ == "__main__":
    raise SystemExit(main())
